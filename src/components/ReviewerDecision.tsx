"use client";

import { useMemo, useState, useSyncExternalStore } from "react";
import {
  clear,
  DECISION_LABELS,
  DECISION_OPTIONS,
  load,
  save,
  type DecisionStorage,
  type DecisionValue,
  type SavedDecision,
} from "@/lib/decisions";

const DEMO_NOTICE =
  "Demo only: this decision is saved in this browser only. It is not sent to a server, not shared across devices, and not a formal audit record.";

const REVIEWER_NOTICE =
  "This is a human reviewer's recorded decision. It does not approve payments, verify milestone completion, or change funding agreements.";

function getBrowserStorage(): DecisionStorage | null {
  try {
    if (typeof window === "undefined") {
      return null;
    }
    return window.localStorage;
  } catch {
    return null;
  }
}

interface DecisionStore {
  subscribe: (listener: () => void) => () => void;
  getSnapshot: () => SavedDecision | null;
  getServerSnapshot: () => SavedDecision | null;
  refresh: () => void;
}

// A tiny external store over localStorage. useSyncExternalStore renders the
// server snapshot (null) while hydrating, so localStorage is only read after
// mount, avoiding server/client hydration mismatches.
function createDecisionStore(evaluationId: string): DecisionStore {
  const listeners = new Set<() => void>();
  let value: SavedDecision | null = null;
  let initialized = false;

  function read(): SavedDecision | null {
    const storage = getBrowserStorage();
    return storage ? load(storage, evaluationId) : null;
  }

  return {
    subscribe(listener) {
      listeners.add(listener);
      return () => {
        listeners.delete(listener);
      };
    },
    getSnapshot() {
      if (!initialized) {
        value = read();
        initialized = true;
      }
      return value;
    },
    getServerSnapshot() {
      return null;
    },
    refresh() {
      value = read();
      initialized = true;
      listeners.forEach((listener) => listener());
    },
  };
}

export default function ReviewerDecision({
  evaluationId,
}: {
  evaluationId: string;
}) {
  const store = useMemo(
    () => createDecisionStore(evaluationId),
    [evaluationId],
  );
  const saved = useSyncExternalStore(
    store.subscribe,
    store.getSnapshot,
    store.getServerSnapshot,
  );

  // undefined means "not edited yet": follow the stored decision.
  const [draft, setDraft] = useState<DecisionValue | null | undefined>(
    undefined,
  );
  const [saveFailed, setSaveFailed] = useState(false);

  const selected =
    draft === undefined ? (saved ? saved.decision : null) : draft;

  function handleSave() {
    if (selected === null) {
      return;
    }
    const storage = getBrowserStorage();
    const result = storage ? save(storage, evaluationId, selected) : null;
    if (result) {
      store.refresh();
      setSaveFailed(false);
    } else {
      setSaveFailed(true);
    }
  }

  function handleClear() {
    const storage = getBrowserStorage();
    if (storage) {
      clear(storage, evaluationId);
    }
    store.refresh();
    setDraft(null);
    setSaveFailed(false);
  }

  const radioGroupName = `reviewer-decision-${evaluationId}`;

  return (
    <section className="flex flex-col gap-4 rounded border border-zinc-300 p-4 dark:border-zinc-700">
      <h4 className="text-lg font-semibold">Human reviewer decision</h4>

      <p className="text-sm leading-relaxed text-zinc-600 dark:text-zinc-400">
        {DEMO_NOTICE}
      </p>
      <p className="text-sm leading-relaxed text-zinc-600 dark:text-zinc-400">
        {REVIEWER_NOTICE}
      </p>
      <p className="text-sm leading-relaxed text-zinc-600 dark:text-zinc-400">
        The evaluation above is advisory and generated by AI. The decision is
        recorded by you, the human reviewer.
      </p>

      <fieldset className="flex flex-col gap-2">
        <legend className="font-medium">Your decision</legend>
        {DECISION_OPTIONS.map((value) => (
          <label key={value} className="flex items-center gap-2">
            <input
              type="radio"
              name={radioGroupName}
              value={value}
              checked={selected === value}
              onChange={() => setDraft(value)}
            />
            {DECISION_LABELS[value]}
          </label>
        ))}
      </fieldset>

      <div className="flex flex-wrap gap-2">
        <button
          type="button"
          onClick={handleSave}
          disabled={selected === null}
          className="rounded bg-black px-4 py-2 font-medium text-white hover:bg-zinc-800 disabled:opacity-50 dark:bg-white dark:text-black dark:hover:bg-zinc-200"
        >
          Save decision
        </button>
        <button
          type="button"
          onClick={handleClear}
          className="rounded border border-zinc-300 px-4 py-2 dark:border-zinc-700"
        >
          Clear decision
        </button>
      </div>

      {saved && (
        <p role="status" className="text-sm">
          Decision recorded: {DECISION_LABELS[saved.decision]} —{" "}
          {new Date(saved.savedAt).toLocaleString()}
        </p>
      )}

      {saveFailed && (
        <p role="alert" className="text-sm text-red-600 dark:text-red-400">
          Your decision could not be saved in this browser.
        </p>
      )}
    </section>
  );
}
